// Fork-only: stamps the build with the git commit and time, so the running
// app can say which build you are looking at (see NavbarComponent). Runs
// automatically before `npm run build` / `npm start` (the pre* npm hooks).
// Writes src/env/build-info.ts, which is gitignored like src/env/env.ts.

import {execSync} from 'node:child_process';
import {mkdirSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function git(command)
{
	try {
		return execSync(`git ${command}`, {cwd: root, stdio: ['ignore', 'pipe', 'ignore']}).toString().trim();
	} catch {
		return '';
	}
}

const commit = git('rev-parse --short HEAD') || 'unknown';
const dirty = git('status --porcelain') !== '';

const source = `// Generated by scripts/write-build-info.mjs - do not edit or commit.
export const buildInfo = {
	commit: ${JSON.stringify(commit)},
	dirty: ${dirty},
	builtAt: ${JSON.stringify(new Date().toISOString())},
};
`;

const target = join(root, 'src', 'env', 'build-info.ts');
mkdirSync(dirname(target), {recursive: true});
writeFileSync(target, source);
console.log(`build-info: ${commit}${dirty ? '+' : ''} @ ${new Date().toISOString()}`);
